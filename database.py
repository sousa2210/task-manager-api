
import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.getenv("DATABASE_URL")

DATABASE_PATH = Path(
    os.getenv(
        "DATABASE_PATH",
        str(Path(__file__).resolve().parent / "tasks.db"),
    )
)


class ConnectionAdapter:
    """Adapta os comandos SQL para SQLite ou PostgreSQL."""

    def __init__(self, connection, is_postgres=False):
        self.connection = connection
        self.is_postgres = is_postgres

    def execute(self, query, parameters=()):
        if self.is_postgres:
            query = query.replace("?", "%s")

        return self.connection.execute(query, parameters)

    def __getattr__(self, name):
        return getattr(self.connection, name)


@contextmanager
def get_connection():
    if DATABASE_URL:
        connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
        )
        adapter = ConnectionAdapter(connection, is_postgres=True)
    else:
        connection = sqlite3.connect(DATABASE_PATH)
        connection.row_factory = sqlite3.Row
        adapter = ConnectionAdapter(connection)

    try:
        yield adapter
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def initialize_database():
    with get_connection() as connection:

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL,
                password_hash TEXT NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
            if DATABASE_URL
            else """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                email TEXT NOT NULL UNIQUE COLLATE NOCASE,
                password_hash TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS tasks (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                completed INTEGER NOT NULL DEFAULT 0,
                user_id INTEGER REFERENCES users(id)
            )
            """
            if DATABASE_URL
            else """
            CREATE TABLE IF NOT EXISTS tasks (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                completed INTEGER NOT NULL DEFAULT 0
            )
            """
        )

        if DATABASE_URL:
            connection.execute(
                """
                CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
                ON users (LOWER(email))
                """
            )

            connection.execute(
                """
                ALTER TABLE tasks
                ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id)
                """
            )
        else:
            task_columns = {
                row["name"]
                for row in connection.execute(
                    "PRAGMA table_info(tasks)"
                ).fetchall()
            }

            if "user_id" not in task_columns:
                connection.execute(
                    "ALTER TABLE tasks ADD COLUMN user_id INTEGER REFERENCES users(id)"
                )
